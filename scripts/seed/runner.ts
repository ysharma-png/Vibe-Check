/**
 * Seed Runner Pipeline
 * Orchestrates `seed:demo` and `seed:wipe-demo` commands.
 * Supports Supabase Postgres remote batched execution and local in-memory dataset synchronization.
 */

import fs from "fs";
import path from "path";
import dotenv from "dotenv";
import { SeededPRNG } from "./prng";
import { generateCreators } from "./generators/creators";
import { generatePortfolioItems } from "./generators/portfolio";
import { generateBriefsAndEngagements } from "./generators/briefs";
import { auditSeedDataset } from "./report";

dotenv.config({ path: ".env.local" });
dotenv.config({ path: ".env" });

const args = process.argv.slice(2);
const isWipeOnly = args.includes("--wipe-demo");

async function runSeedPipeline() {
  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const isSupabaseConfigured =
    Boolean(supabaseUrl && serviceRoleKey && !supabaseUrl.includes("placeholder"));

  if (isWipeOnly) {
    console.log("==================================================================");
    console.log("CACHEFLOW: PURGING DEMO ROWS (--wipe-demo)");
    console.log("==================================================================");

    if (isSupabaseConfigured) {
      const { createClient } = await import("@supabase/supabase-js");
      const supabase = createClient(supabaseUrl!, serviceRoleKey!);

      console.log("Removing demo records from Supabase tables where is_demo = true...");
      const { error: briefsErr } = await supabase
        .from("creative_briefs")
        .delete()
        .eq("is_demo", true);
      if (briefsErr) console.warn("Notice: briefs wipe:", briefsErr.message);

      const { error: profilesErr } = await supabase
        .from("profiles")
        .delete()
        .eq("is_demo", true);
      if (profilesErr) console.warn("Notice: profiles wipe:", profilesErr.message);

      console.log("✓ Remote Supabase demo rows successfully wiped (real user accounts preserved).");
    }

    // Wipe local seed snapshot demo records
    const snapshotPath = path.join(process.cwd(), "supabase", "seed-snapshot.json");
    if (fs.existsSync(snapshotPath)) {
      fs.unlinkSync(snapshotPath);
      console.log(`✓ Removed local snapshot ${snapshotPath}`);
    }

    console.log("Wipe completed successfully.\n");
    return;
  }

  console.log("==================================================================");
  console.log("CACHEFLOW: GENERATING IDEMPOTENT DEMO SEED DATASET");
  console.log("==================================================================");

  const prng = new SeededPRNG();
  console.log("1. Generating 140 fictional creators meeting coverage matrix...");
  const creatorsWithMeta = generateCreators(prng);
  const creators = creatorsWithMeta.map((c) => c.creator);

  console.log("2. Generating ~700 realistic portfolio items with multi-stage DAGs...");
  const portfolioItems = generatePortfolioItems(creatorsWithMeta, prng);

  console.log("3. Generating 40 brands, 60 briefs, proposals, and engagements...");
  const { briefs, proposals, engagements } = generateBriefsAndEngagements(
    creatorsWithMeta,
    prng
  );

  console.log(`\nGenerated Entities:`);
  console.log(`- Creators:       ${creators.length}`);
  console.log(`- Portfolio Items:${portfolioItems.length}`);
  console.log(`- Creative Briefs:${briefs.length}`);
  console.log(`- Proposals:      ${proposals.length}`);
  console.log(`- Engagements:    ${engagements.length}`);

  // Sync to local data files (src/data/seed/dataset.ts)
  console.log("\n4. Synchronizing local TypeScript seed dataset for offline & dev mode...");
  const seedDir = path.join(process.cwd(), "src", "data", "seed");
  if (!fs.existsSync(seedDir)) fs.mkdirSync(seedDir, { recursive: true });

  const datasetCode = `// Autogenerated by scripts/seed/runner.ts
import { CreatorProfile, PortfolioItem, CreativeBrief } from "@/types/schema";

export const SEED_CREATORS: readonly CreatorProfile[] = ${JSON.stringify(creators, null, 2)} as const;

export const SEED_PORTFOLIO: readonly PortfolioItem[] = ${JSON.stringify(portfolioItems, null, 2)} as const;

export const SEED_BRIEFS: readonly CreativeBrief[] = ${JSON.stringify(briefs, null, 2)} as const;
`;
  fs.writeFileSync(path.join(seedDir, "dataset.ts"), datasetCode, "utf8");

  // Save snapshot to supabase/seed-snapshot.json
  const supabaseDir = path.join(process.cwd(), "supabase");
  if (!fs.existsSync(supabaseDir)) fs.mkdirSync(supabaseDir, { recursive: true });

  const snapshotPath = path.join(supabaseDir, "seed-snapshot.json");
  fs.writeFileSync(
    snapshotPath,
    JSON.stringify(
      {
        timestamp: new Date().toISOString(),
        seed: process.env.SEED || "cacheflow-2026",
        creatorsCount: creators.length,
        portfolioCount: portfolioItems.length,
        briefsCount: briefs.length,
        proposalsCount: proposals.length,
        engagementsCount: engagements.length,
        creators,
        portfolioItems,
        briefs,
        proposals,
        engagements,
      },
      null,
      2
    ),
    "utf8"
  );
  console.log(`✓ Snapshot persisted to ${snapshotPath}`);

  // Remote Supabase batched inserts if connected
  if (isSupabaseConfigured) {
    console.log("\n5. Remote Supabase connection detected. Running batched upserts...");
    try {
      const { createClient } = await import("@supabase/supabase-js");
      const supabase = createClient(supabaseUrl!, serviceRoleKey!);

      // Batch size 50
      const BATCH = 50;
      for (let i = 0; i < creators.length; i += BATCH) {
        const chunk = creators.slice(i, i + BATCH);
        await supabase.from("profiles").upsert(
          chunk.map((c) => ({
            id: c.id,
            role: "creator",
            email: `${c.handle.replace("@", "")}@demo.cacheflow.ai`,
            full_name: c.name,
            display_name: c.name,
            handle: c.handle.replace("@", ""),
            bio: c.bio,
            location: c.location,
            verified_identity: c.verified.identity,
            deterministic_pipeline: c.verified.reproduciblePipeline,
            commercial_clearance_cleared: c.verified.commercialLicense,
            rating: 5.0,
            completed_projects: c.stats.projectsCompleted,
            hourly_rate_usd: c.startingRateUsd,
            primary_tools: c.primaryTools,
            specializations: c.specializations,
            skills: c.skills,
            is_demo: true,
          }))
        );
      }
      console.log(`✓ Upserted ${creators.length} profiles to Supabase Postgres.`);
    } catch (err: unknown) {
      console.warn("Notice: remote upsert warning:", err instanceof Error ? err.message : err);
    }
  }

  // 6. Run audit report
  console.log("\n6. Running dataset coverage matrix audit...");
  const auditPassed = auditSeedDataset();

  if (!auditPassed) {
    console.error("Warning: Dataset audit flagged one or more targets below threshold.");
    process.exit(1);
  }
}

runSeedPipeline().catch((err) => {
  console.error("Seed execution failed:", err);
  process.exit(1);
});
